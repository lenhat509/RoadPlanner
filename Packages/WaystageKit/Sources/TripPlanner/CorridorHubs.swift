/// A city on the highway network that a route can be asked to pass through, to find a different
/// corridor between two places ("via Las Vegas").
public struct CorridorHub: Hashable, Sendable {
    public var name: String
    public var coordinate: GeoCoordinate

    public init(name: String, latitude: Double, longitude: Double) {
        self.name = name
        coordinate = GeoCoordinate(latitude: latitude, longitude: longitude)
    }
}

